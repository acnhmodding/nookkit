#!/usr/bin/env python3
"""Harvests the save schema of an ACNH romfs into data/save-<build>.toml.

System/Smmh/<file>_<revision>.byml describes every struct of one save file: its size, alignment and members,
each with an offset, a type, an element size and up to two array lengths. Type and member names are stored as
murmur3 x86_32 hashes, so they are resolved against a names list, one name per line. Hashes without a known
name become Unknown_<HASH> types and unknown_<hash> members. Types without members are leaves, such as
primitives, enums and external types.

usage: harvest_save.py <romfs>/System/Smmh <names.txt> <out.toml>
"""

import os
import struct
import sys

REVISION = '655400_655362'

TYPE_NAME = '5c65d8b5'
SIZE = 'b4a58247'
ALIGN = '4a4cb5b4'
MEMBERS = 'a2fb4a94'
NAME = '25efa387'
OFFSET = 'a7bb2e42'
LENGTH1 = '1e0eae33'
LENGTH2 = 'a9f41a61'


def mm3(text):
    data = text.encode()
    c1, c2 = 0xCC9E2D51, 0x1B873593
    h = 0
    rotl = lambda x, r: ((x << r) | (x >> (32 - r))) & 0xFFFFFFFF
    body = len(data) // 4 * 4
    for i in range(0, body, 4):
        k = int.from_bytes(data[i:i + 4], 'little')
        h ^= rotl(k * c1 & 0xFFFFFFFF, 15) * c2 & 0xFFFFFFFF
        h = (rotl(h, 13) * 5 + 0xE6546B64) & 0xFFFFFFFF
    tail = data[body:]
    if tail:
        k = int.from_bytes(tail, 'little')
        h ^= rotl(k * c1 & 0xFFFFFFFF, 15) * c2 & 0xFFFFFFFF
    h ^= len(data)
    h ^= h >> 16
    h = h * 0x85EBCA6B & 0xFFFFFFFF
    h ^= h >> 13
    h = h * 0xC2B2AE35 & 0xFFFFFFFF
    return h ^ (h >> 16)


# Only the node types the Smmh files use
def read_byml(b):
    assert b[:2] == b'YB', 'not a little-endian BYML'
    keys_at, strings_at, root = struct.unpack_from('<III', b, 4)

    def table(at):
        if not at:
            return []
        count = struct.unpack_from('<I', b, at)[0] >> 8
        offsets = struct.unpack_from(f'<{count}I', b, at + 4)
        return [b[at + o:b.index(b'\0', at + o)].decode() for o in offsets]

    keys, strings = table(keys_at), table(strings_at)

    def value(kind, raw):
        if kind == 0xA0:
            return strings[raw]
        if kind == 0xD0:
            return bool(raw)
        if kind == 0xD1:
            return struct.unpack('<i', struct.pack('<I', raw))[0]
        if kind == 0xD3:
            return raw
        if kind == 0xD4:
            return struct.unpack_from('<q', b, raw)[0]
        if kind == 0xD5:
            return struct.unpack_from('<Q', b, raw)[0]
        if kind in (0xC0, 0xC1):
            return node(raw)
        raise ValueError(f'unsupported BYML node type {kind:#x}')

    def node(at):
        kind = b[at]
        count = struct.unpack_from('<I', b, at)[0] >> 8
        if kind == 0xC0:
            kinds = b[at + 4:at + 4 + count]
            values = (at + 4 + count + 3) & ~3
            return [value(kinds[i], struct.unpack_from('<I', b, values + 4 * i)[0]) for i in range(count)]
        out = {}
        for i in range(count):
            entry = at + 4 + 8 * i
            key = struct.unpack_from('<I', b, entry)[0] & 0xFFFFFF
            out[keys[key]] = value(b[entry + 3], struct.unpack_from('<I', b, entry + 4)[0])
        return out

    return node(root)


def main():
    smmh_dir, names_path, out_path = sys.argv[1:4]
    names = {}
    for line in open(names_path, encoding='utf-8'):
        name = line.strip()
        if name and not name.startswith('#'):
            names[mm3(name)] = name

    files = sorted(f for f in os.listdir(smmh_dir) if f.endswith(f'_{REVISION}.byml'))
    defined, leaves, conflicts = {}, {}, []
    for file in files:
        for t in read_byml(open(os.path.join(smmh_dir, file), 'rb').read()):
            entry = (t[SIZE], t[ALIGN], [
                (m[OFFSET], m[NAME], m[TYPE_NAME], m[SIZE], m[ALIGN], m.get(LENGTH1, 1), m.get(LENGTH2))
                for m in t[MEMBERS]
            ])
            if defined.setdefault(t[TYPE_NAME], entry) != entry:
                conflicts.append(f'{file}: type {t[TYPE_NAME]:08x} differs from an earlier file')
            for m in t[MEMBERS]:
                leaves.setdefault(m[TYPE_NAME], set()).add((m[SIZE], m[ALIGN]))

    def type_name(h):
        return names.get(h, f'Unknown_{h:08X}')

    lines = [f'# Generated by tools/harvest_save.py from the romfs System/Smmh *_{REVISION} schemas', '']
    unnamed_types, unnamed_members = set(), set()
    for h in sorted(set(defined) | set(leaves), key=type_name):
        if h not in names:
            unnamed_types.add(h)
        lines.append(f'["{type_name(h)}"]')
        if h in defined:
            size, align, members = defined[h]
        else:
            if len(leaves[h]) != 1:
                conflicts.append(f'leaf {type_name(h)} has several sizes: {sorted(leaves[h])}')
            (size, align), members = min(leaves[h]), []
        lines.append(f'size = {size:#x}')
        lines.append(f'align = {align}')
        end = 0
        for offset, name, kind, elem, elem_align, length1, length2 in sorted(members):
            if name not in names:
                unnamed_members.add(name)
            if kind in defined and defined[kind][:2] != (elem, elem_align):
                conflicts.append(f'{type_name(h)}: member {name:08x} disagrees with its type size')
            if offset < end:
                conflicts.append(f'{type_name(h)}: member {name:08x} overlaps the previous one')
            end = offset + elem * length1 * (length2 or 1)
            dims = '' if length1 == 1 and not length2 else f' {length1}' + (f'x{length2}' if length2 else '')
            member = names.get(name, f'unknown_{name:08x}')
            lines.append(f'field.{member} = "{offset:#x} {type_name(kind)}{dims}"')
        if end > size:
            conflicts.append(f'{type_name(h)}: members end past its size')
        lines.append('')
    open(out_path, 'w', newline='\n').write('\n'.join(lines))

    print(f'files: {len(files)}, types: {len(defined)}, leaves: {len(set(leaves) - set(defined))}, '
          f'unnamed types: {len(unnamed_types)}, unnamed members: {len(unnamed_members)}')
    for c in conflicts:
        print('conflict', c)


if __name__ == '__main__':
    main()
