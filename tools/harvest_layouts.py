#!/usr/bin/env python3
"""Harvests the parts panes of every layout in an ACNH romfs into data/layouts-<build>.toml.

Each Layout/<name>.Nin_NX_NVN.zs is zstd -> SARC -> <name>.arc -> blyt/*.bflyt. Per bflyt it records the
layout's own cnt1 control_name and its parts panes (pane name -> part layout). Parts nested inside a part
layout belong to that layout, so only the parts in a bflyt's own pane tree are listed.

Needs zstd and nnbfl on PATH.
usage: harvest_layouts.py <romfs>/Layout <out.toml>
"""

import concurrent.futures
import json
import os
import struct
import subprocess
import sys
import tempfile


def read_sarc(b):
    assert b[:4] == b'SARC', 'not a SARC'
    count = struct.unpack_from('<H', b, 0x1A)[0]
    data_start = struct.unpack_from('<I', b, 0xC)[0]
    names = 0x20 + count * 16 + 8
    out = {}
    for i in range(count):
        _, attr, start, end = struct.unpack_from('<IIII', b, 0x20 + i * 16)
        at = names + (attr & 0xFFFFFF) * 4
        out[b[at:b.index(b'\0', at)].decode()] = b[data_start + start:data_start + end]
    return out


def parts(node, out):
    pane = node['Pane']
    data = pane['data']
    if 'PartsPane' in data:
        p = data['PartsPane']
        out.append((p['base']['pane_name'], p['o_layout_name']))
    for child in pane.get('children', []):
        parts(child, out)


def harvest(path):
    raw = subprocess.run(['zstd', '-d', '-c', path], check=True, capture_output=True).stdout
    layouts = {}
    with tempfile.TemporaryDirectory() as tmp:
        for arc in read_sarc(raw).values():
            for name, data in read_sarc(arc).items():
                if not name.endswith('.bflyt'):
                    continue
                bflyt = os.path.join(tmp, 'in.bflyt')
                open(bflyt, 'wb').write(data)
                subprocess.run(['nnbfl', 'bflyt', 'extract', bflyt], check=True, capture_output=True)
                d = json.load(open(os.path.join(tmp, 'in.json')))
                found = []
                for root in d['nodes']:
                    parts(root, found)
                source = d.get('control_source')
                control = source['data']['control_name'] if source else ''
                layouts[os.path.basename(name)[:-len('.bflyt')]] = (control, found)
    return layouts


def key(s):
    return s if s.replace('_', '').isalnum() else json.dumps(s)


def main():
    layout_dir, out_path = sys.argv[1:3]
    archives = sorted(f for f in os.listdir(layout_dir) if f.endswith('.Nin_NX_NVN.zs'))
    layouts, errors, skipped = {}, [], []
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count()) as pool:
        jobs = {pool.submit(harvest, os.path.join(layout_dir, a)): a for a in archives}
        for job in concurrent.futures.as_completed(jobs):
            try:
                layouts.update(job.result())
            except AssertionError:
                skipped.append(jobs[job])
            except Exception as e:
                errors.append(f'{jobs[job]}: {e}')

    lines = ['# Generated by tools/harvest_layouts.py from the romfs Layout archives', '']
    total, duplicates = 0, []
    for name in sorted(layouts):
        control, found = layouts[name]
        lines.append(f'[{key(name)}]')
        if control:
            lines.append(f'control = {json.dumps(control)}')
        seen = set()
        for pane, part in found:
            if pane in seen:
                duplicates.append(f'{name}/{pane}')
                continue
            seen.add(pane)
            lines.append(f'parts.{key(pane)} = {json.dumps(part)}')
            total += 1
        lines.append('')
    open(out_path, 'w').write('\n'.join(lines))

    print(f'archives: {len(archives)}, layouts: {len(layouts)}, parts panes: {total}, errors: {len(errors)}')
    for s in sorted(skipped):
        print('skipped, not a layout SARC:', s)
    for e in errors:
        print('error', e)
    for d in duplicates:
        print('duplicate pane name, kept the first:', d)


if __name__ == '__main__':
    main()
