// Args: out_path game_version manifest_path...
// @category ACNH

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.data.*;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.Parameter;
import ghidra.program.model.symbol.*;
import java.nio.file.*;
import java.util.*;

public class ExportSymbols extends GhidraScript {

    private static final long FINGERPRINT_OFFSET = 0x3f60000L;
    private static final int FINGERPRINT_LEN = 0x10000;
    private static final List<String> KINDS = List.of("fn", "vtable", "data");

    @Override
    public void run() throws Exception {
        String[] a = getScriptArgs();
        Path out = Paths.get(a[0]);
        String version = a[1];

        Map<String, TreeMap<String, Long>> sections = new LinkedHashMap<>();
        TreeMap<String, String> signatures = new TreeMap<>();
        List<String> unchecked = new ArrayList<>();

        for (String k : KINDS) {
            sections.put(k, new TreeMap<>());
        }

        List<String> problems = new ArrayList<>();

        Map<String, List<Symbol>> byName = new HashMap<>();
        for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(true)) {
            byName.computeIfAbsent(s.getName(true), k -> new ArrayList<>()).add(s);
        }

        Address base = currentProgram.getImageBase();
        for (int m = 2; m < a.length; m++) {
            for (String raw : Files.readAllLines(Paths.get(a[m]))) {
                String line = raw.trim();

                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }

                String[] f = line.split("\t", 2);

                if (f.length != 2 || !KINDS.contains(f[0])) {
                    problems.add("bad manifest line: " + raw);
                    continue;
                }

                String kind = f[0], name = f[1];
                String label = name;

                Set<Address> hits = new LinkedHashSet<>();

                for (Symbol s : byName.getOrDefault(label, List.of())) {
                    // A thunk shows its target's name, it's never the function a manifest means
                    Function fn = getFunctionAt(s.getAddress());
                    boolean isFn = fn != null && !fn.isThunk() && s.getSymbolType() == SymbolType.FUNCTION;

                    if (kind.equals("fn") == isFn) {
                        hits.add(s.getAddress());
                    }
                }

                if (hits.isEmpty()) {
                    problems.add("missing " + kind + " " + label);
                    continue;
                }

                if (hits.size() > 1) {
                    problems.add("ambiguous " + kind + " " + label + " " + hits);
                    continue;
                }

                Address at = hits.iterator().next();
                if (kind.equals("fn")) {
                    String sig = signature(getFunctionAt(at));

                    if (sig != null) {
                        signatures.put(name, sig);
                    } else {
                        unchecked.add(name);
                    }
                }

                long offset = at.subtract(base);
                Long prev = sections.get(kind).put(name, offset);

                if (prev != null && prev != offset) {
                    problems.add("conflicting " + kind + " " + name);
                }
            }
        }

        if (!problems.isEmpty()) {
            for (String p : problems) {
                println("ERROR " + p);
            }

            println("not written: " + problems.size() + " problem(s)");
            return;
        }

        byte[] window = new byte[FINGERPRINT_LEN];
        currentProgram.getMemory().getBytes(base.add(FINGERPRINT_OFFSET), window);
        long hash = 0xcbf29ce484222325L;

        for (byte b : window) {
            hash = (hash ^ (b & 0xff)) * 0x100000001b3L;
        }

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by ExportSymbols.java from the Ghidra labels; do not edit by hand.\n");
        sb.append("game_version = \"").append(version).append("\"\n");
        sb.append(String.format("rodata_hash = 0x%016x\n", hash));
        int count = 0;

        for (Map.Entry<String, TreeMap<String, Long>> s : sections.entrySet()) {
            if (s.getValue().isEmpty()) {
                continue;
            }

            sb.append("\n[").append(s.getKey()).append("]\n");
            for (Map.Entry<String, Long> e : s.getValue().entrySet()) {
                sb.append('"').append(e.getKey()).append("\" = ").append(String.format("0x%x", e.getValue())).append('\n');
                count++;
            }
        }

        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, sb.toString());
        println("wrote " + count + " symbols to " + out);

        StringBuilder sigs = new StringBuilder();
        sigs.append("# Generated by ExportSymbols.java from the Ghidra prototypes; do not edit by hand.\n");
        sigs.append("\n[fn]\n");

        for (Map.Entry<String, String> e : signatures.entrySet()) {
            sigs.append('"').append(e.getKey()).append("\" = \"").append(e.getValue()).append("\"\n");
        }

        Path sigOut = out.toAbsolutePath().getParent().resolve("signatures.toml");
        Files.writeString(sigOut, sigs.toString());
        println("wrote " + signatures.size() + " signatures to " + sigOut);

        for (String n : unchecked) {
            println("unchecked (no hand-set prototype): " + n);
        }
    }

    private static String signature(Function f) {
        SourceType src = f.getSignatureSource();

        if (src != SourceType.USER_DEFINED && src != SourceType.IMPORTED) {
            return null;
        }

        if (f.hasVarArgs()) {
            return null;
        }

        List<String> args = new ArrayList<>();

        for (Parameter p : f.getParameters()) {
            String t = abi(p.getDataType());
            if (t == null || t.equals("void")) {
                return null;
            }

            args.add(t);
        }

        String ret = abi(f.getReturnType());
        if (ret == null) {
            return null;
        }

        return String.join(", ", args) + " -> " + ret;
    }

    private static String abi(DataType dt) {
        while (dt instanceof TypeDef td) {
            dt = td.getBaseDataType();
        }

        if (dt == null) {
            return null;
        }

        if (dt instanceof VoidDataType || dt == DataType.VOID) {
            return "void";
        }

        if (dt instanceof Pointer) {
            return "ptr";
        }

        if (dt instanceof Structure || dt instanceof Union || dt instanceof Array) {
            return null;
        }

        int len = dt.getLength();
        if (dt instanceof AbstractFloatDataType) {
            return len == 4 ? "f32" : len == 8 ? "f64" : null;
        }

        if (dt instanceof ghidra.program.model.data.Enum || dt instanceof AbstractIntegerDataType || dt instanceof BooleanDataType
                || dt instanceof Undefined || dt instanceof DefaultDataType) {
            return switch (len) {
                case 1 ->
                    "i8";
                case 2 ->
                    "i16";
                case 4 ->
                    "i32";
                case 8 ->
                    "i64";
                default ->
                    null;
            };
        }

        return null;
    }
}
